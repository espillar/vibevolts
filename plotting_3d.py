import numpy as np
from datetime import datetime
from typing import Any, List, Optional

import plotly.graph_objects as go
from astropy.time import Time
from astropy.coordinates import GCRS, EarthLocation
import astropy.units as u

from constants import EARTH_RADIUS


def add_sphere_trace(
    fig: go.Figure,
    radius: float = EARTH_RADIUS,
    name: str = 'Earth',
    colorscale: str = 'Blues',
    opacity: float = 0.5,
    resolution: int = 100,
) -> go.Figure:
    """Adds a 3D sphere surface trace to an existing Plotly figure."""
    u_sphere = np.linspace(0, 2 * np.pi, resolution)
    v_sphere = np.linspace(0, np.pi, resolution)
    x = radius * np.outer(np.cos(u_sphere), np.sin(v_sphere))
    y = radius * np.outer(np.sin(u_sphere), np.sin(v_sphere))
    z = radius * np.outer(np.ones_like(u_sphere), np.cos(v_sphere))
    fig.add_trace(go.Surface(
        x=x, y=y, z=z,
        colorscale=colorscale, showscale=False, opacity=opacity, name=name
    ))
    return fig


def tag_demo_figure(fig: go.Figure, demo_name: str) -> go.Figure:
    """Adds a standard 'Generated by: <demo_name>' subtitle annotation to a figure."""
    fig.add_annotation(
        text=f"Generated by: {demo_name}",
        xref="paper", yref="paper",
        x=0.5, y=1.01,
        showarrow=False,
        font=dict(size=10, color="gray"),
        xanchor="center", yanchor="bottom"
    )
    return fig


def apply_3d_scene_layout(
    fig: go.Figure,
    title: str,
    axis_unit: str = ' (m)',
    legend_title: Optional[str] = None,
    **extra_layout,
) -> go.Figure:
    """Applies standard 3D scene axes, aspectmode='data', and compact margins."""
    layout_kwargs = dict(
        title=title,
        scene=dict(
            xaxis_title=f'X{axis_unit}',
            yaxis_title=f'Y{axis_unit}',
            zaxis_title=f'Z{axis_unit}',
            aspectmode='data',
        ),
        margin=dict(r=20, b=10, l=10, t=40),
    )
    if legend_title is not None:
        layout_kwargs['legend_title_text'] = legend_title
    layout_kwargs.update(extra_layout)
    fig.update_layout(**layout_kwargs)
    return fig


def add_vector_traces(
    fig: go.Figure,
    origins: np.ndarray,
    vectors: np.ndarray,
    scale: float = 1.0,
    color: str = 'red',
    width: int = 3,
    name: Optional[str] = None,
    normalize: bool = True,
) -> go.Figure:
    """Adds 3D line segments from origins along vectors (scaled by scale) to a figure."""
    orig_arr = np.atleast_2d(np.asarray(origins, dtype=float))
    vec_arr = np.atleast_2d(np.asarray(vectors, dtype=float))
    if orig_arr.shape[0] == 1 and vec_arr.shape[0] > 1:
        orig_arr = np.repeat(orig_arr, vec_arr.shape[0], axis=0)
    if normalize:
        norms = np.linalg.norm(vec_arr, axis=1, keepdims=True)
        vec_arr = np.where(norms > 0, vec_arr / np.where(norms > 0, norms, 1.0), 0.0)
    ends = orig_arr + vec_arr * scale
    xs, ys, zs = [], [], []
    for start, end in zip(orig_arr, ends):
        xs.extend([start[0], end[0], None])
        ys.extend([start[1], end[1], None])
        zs.extend([start[2], end[2], None])
    fig.add_trace(go.Scatter3d(
        x=xs, y=ys, z=zs,
        mode='lines',
        line=dict(color=color, width=width),
        name=name or '',
        showlegend=name is not None,
    ))
    return fig


def plot_3d_scatter(
    positions: np.ndarray,
    title: str,
    plot_time: datetime,
    labels: Optional[List[str]] = None,
    marker_size: int = 1,
    trace_name: str = 'Points',
    marker_color: Optional[str] = None
) -> go.Figure:
    """
    Creates a 3D plot of object positions.
    """
    if positions.ndim != 2 or positions.shape[1] != 3:
        raise ValueError("positions array must have shape (n, 3).")

    fig = go.Figure()

    marker_dict = dict(
        size=marker_size,
        opacity=0.8
    )
    if marker_color:
        marker_dict['color'] = marker_color
    else:
        marker_dict['color'] = np.arange(len(positions))
        marker_dict['colorscale'] = 'Viridis'

    fig.add_trace(go.Scatter3d(
        x=positions[:, 0], y=positions[:, 1], z=positions[:, 2],
        mode='markers',
        marker=marker_dict,
        text=labels,
        hoverinfo='text' if labels else 'none',
        name=trace_name
    ))

    add_sphere_trace(fig, radius=EARTH_RADIUS, name='Earth')

    theta = np.linspace(0, 2 * np.pi, 100)
    x_eq = EARTH_RADIUS * np.cos(theta)
    y_eq = EARTH_RADIUS * np.sin(theta)
    z_eq = np.zeros_like(theta)
    fig.add_trace(go.Scatter3d(
        x=x_eq, y=y_eq, z=z_eq, mode='lines',
        line=dict(color='green', width=3), name='Equator'
    ))

    fig.add_trace(go.Scatter3d(
        x=[0], y=[0], z=[EARTH_RADIUS * 1.1], mode='text',
        text=['N'], textfont=dict(size=15, color='red'), name='North Pole'
    ))

    lat_es, lon_es = 33.92 * u.deg, -118.42 * u.deg
    el_segundo_loc = EarthLocation.from_geodetic(lon=lon_es, lat=lat_es)
    itrs_coords = el_segundo_loc.get_itrs(obstime=Time(plot_time))
    gcrs_coords = itrs_coords.transform_to(GCRS(obstime=Time(plot_time)))
    es_pos = gcrs_coords.cartesian.xyz.to(u.m).value * 1.05
    fig.add_trace(go.Scatter3d(
        x=[es_pos[0]], y=[es_pos[1]], z=[es_pos[2]], mode='text',
        text=['ES'], textfont=dict(size=15, color='yellow'), name='El Segundo'
    ))

    apply_3d_scene_layout(fig, title, legend_title='Objects')

    return fig


def plot_pointing_vectors(
    data_struct: Any,
    title: str,
    plot_time: Optional[datetime] = None,
) -> go.Figure:
    """Creates a 3D plot of active observers with their current pointing vectors."""
    positions = data_struct.get_detector_positions()
    if len(positions) == 0:
        print("No satellites to plot.")
        return go.Figure()
    det = data_struct.detector
    fig = go.Figure()
    fig.add_trace(go.Scatter3d(
        x=positions[:, 0], y=positions[:, 1], z=positions[:, 2],
        mode='markers', marker=dict(size=5, color='blue', opacity=0.8),
        name='Satellites',
    ))
    if det is not None and len(det.pointing) > 0:
        add_vector_traces(
            fig, positions, det.pointing[:len(positions)],
            scale=0.5 * EARTH_RADIUS, color='red', width=3,
        )
    add_sphere_trace(fig, radius=EARTH_RADIUS, name='Earth')
    return apply_3d_scene_layout(fig, title)
